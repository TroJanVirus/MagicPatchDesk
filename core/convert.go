package core

import (
	"bytes"
	"fmt"
	"hash/crc32"
	"path/filepath"
	"strings"
)

// DiffToJMP produces a JMP with file offsets; search records require contextual matching and are not inferred.
func DiffToJMP(original, modified []byte, title string) (string, error) {
	if len(original) > 512<<20 || len(modified) > 512<<20 {
		return "", fmt.Errorf("file too large")
	}
	if title == "" {
		title = "Unknown"
	}
	var out strings.Builder
	out.WriteString("#Jay's Magic Patcher (www.jayxbox.com)\nsystem=Xbox\ngame-title=" + strings.ReplaceAll(title, "\n", " ") + "\nregion=\nversion=")
	info, err := InspectXBE(original)
	if err == nil {
		out.WriteString(info.TitleID + " ")
	}
	out.WriteString(fmt.Sprintf("{%08X}\nauthor=\nnotes=Generated by Magic Patch Desk from stock and modified XBE\n", crc32.ChecksumIEEE(original)))
	for i := 0; i < len(modified) && i < len(original); {
		if original[i] == modified[i] {
			i++
			continue
		}
		start := i
		for i < len(original) && i < len(modified) && original[i] != modified[i] && i-start < 8192 {
			i++
		}
		out.WriteString(fmt.Sprintf("#Diff @ 0x%X\n0x%X:%X\n", start, start, modified[start:i]))
	}
	if len(modified) > len(original) {
		for i := len(original); i < len(modified); i += 8192 {
			end := i + 8192
			if end > len(modified) {
				end = len(modified)
			}
			out.WriteString(fmt.Sprintf("#Appended bytes\nAPPEND:%X\n", modified[i:end]))
		}
	}
	if len(modified) < len(original) {
		return "", fmt.Errorf("JMP cannot encode XBE truncation; use IPS or Xdelta")
	}
	if bytes.Equal(original, modified) {
		return "", fmt.Errorf("no differences")
	}
	return out.String(), nil
}
func PatchTypeFromFilename(name string) string {
	base := filepath.Base(name)
	i := strings.IndexByte(base, '{')
	if i >= 0 {
		if j := strings.IndexByte(base[i+1:], '}'); j >= 0 {
			return strings.TrimSpace(base[i+1 : i+1+j])
		}
	}
	return "Misc"
}
